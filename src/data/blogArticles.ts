export function getBlogArticleBySlug(slug: string): ArticleData | undefined {
  if (!slug) return undefined;
  const cleanSlug = slug.startsWith('/blog/') ? slug : `/blog/${slug.replace(/^\//, '')}`;
  return ALL_ARTICLES.find(
    a => a.slug === cleanSlug || a.slug === slug || a.slug.endsWith(slug) || slug.endsWith(a.slug.replace('/blog/', ''))
  );
}
